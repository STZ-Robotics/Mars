//! Two build jobs: generating the protocol and aliasing libraries.
//!
//! # 1. Protocol constants
//!
//! `../protocol/topics.toml` says of itself that it is the single source of
//! truth and that "nobody writes a topic name by hand in the code". This
//! makes it true on the Rust side: it reads the manifest at compile time and
//! emits the constants. Renaming a topic in the manifest breaks the bridge's
//! build, which is exactly what is wanted.
//!
//! # 2. Library aliases
//!
//! Bridges the naming mismatch between pkg-config and MSVC.
//!
//! conda-forge's `.pc` files are written with the Unix convention: they ask
//! for `-lprotobuf` and `-lzmq`, counting on the linker to prepend `lib`. MSVC
//! does not -- it looks for literal `protobuf.lib` and `zmq.lib` -- while the
//! installed files are called `libprotobuf.lib` and `libzmq.lib`. Linking
//! `gz-transport-sys` dies with
//!
//!     LNK1181: cannot open input file 'protobuf.lib'
//!
//! The `cargo:rustc-link-lib=` lines are emitted by `gz-transport-sys` and
//! there is no way to remove them from here, so instead of fighting the name
//! it is given what it asks for: a hard link with the right name in OUT_DIR,
//! which is added to the linker's search path.
//!
//! If a new LNK1181 shows up, add the name to ALIASES and that is it.
//!
//! Only applies to Windows with MSVC. On Linux and macOS the names already
//! match.

use std::path::{Path, PathBuf};

/// Libraries that have to be exposed without the `lib` prefix.
const ALIASES: &[&str] = &["protobuf", "zmq"];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CONDA_PREFIX");

    generate_protocol();
    alias_libraries();
}

/// Translates ../protocol/topics.toml into Rust constants.
fn generate_protocol() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR")).join("../protocol/topics.toml");
    println!("cargo:rerun-if-changed={}", manifest.display());

    let text = std::fs::read_to_string(&manifest)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", manifest.display()));
    let doc: toml::Value = text.parse().expect("topics.toml is not valid TOML");

    let mut out = String::from(
        "// GENERATED by build.rs from simulationstudio/protocol/topics.toml. Do not edit.\n",
    );

    let s = |k: &str| doc[k].as_str().expect("text field").to_string();
    out += &format!("pub const PROTOCOL_VERSION: &str = {:?};\n", s("protocol_version"));
    out += &format!("pub const WORLD: &str = {:?};\n", s("world"));

    let field = &doc["field"];
    for k in ["length_m", "width_m"] {
        let v = field[k].as_float().expect("the dimensions are decimals");
        out += &format!("pub const FIELD_{}: f64 = {v:?};\n", k.to_uppercase());
    }

    // One constant per topic, with the name derived from its path:
    //   /mars/state/pose  ->  T_MARS_STATE_POSE
    // The glue template's ones carry <name> and are not constants; skipped.
    for group in ["gz", "nt"] {
        let Some(entries) = doc.get(group).and_then(|g| g.as_array()) else { continue };
        for e in entries {
            let topic = e["topic"].as_str().expect("topic is text");
            if topic.contains('<') {
                continue;
            }
            let ident: String = topic
                .trim_start_matches('/')
                .chars()
                .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' })
                .collect();
            out += &format!("pub const T_{ident}: &str = {topic:?};\n");
        }
    }

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("cargo defines OUT_DIR"))
        .join("protocol.rs");
    std::fs::write(&dest, out).expect("could not write protocol.rs");
}

fn alias_libraries() {
    if cfg!(not(all(target_os = "windows", target_env = "msvc"))) {
        return;
    }

    let Some(libdir) = find_conda_libdir() else {
        // Without an environment there is nothing to patch; linking will fail
        // later with a clearer message than anything we could say here.
        return;
    };

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo defines OUT_DIR"));
    let mut done = 0;

    for name in ALIASES {
        // If conda already installs the unprefixed name, leave it alone.
        if libdir.join(format!("{name}.lib")).exists() {
            continue;
        }
        let origin = libdir.join(format!("lib{name}.lib"));
        if !origin.exists() {
            continue;
        }

        let dest = out.join(format!("{name}.lib"));
        // A hard link instead of a copy: these libraries weigh tens of MB and
        // live on the same volume. If it fails (different volumes,
        // permissions), it copies.
        if dest.exists() {
            let _ = std::fs::remove_file(&dest);
        }
        if std::fs::hard_link(&origin, &dest).is_err() {
            std::fs::copy(&origin, &dest).unwrap_or_else(|e| {
                panic!("could not alias {} -> {}: {e}", origin.display(), dest.display())
            });
        }
        done += 1;
    }

    if done > 0 {
        println!("cargo:rustc-link-search=native={}", out.display());
    }
}

/// Library directory of the `mars-sim` conda environment.
fn find_conda_libdir() -> Option<PathBuf> {
    let mut bases: Vec<PathBuf> = Vec::new();
    if let Ok(prefix) = std::env::var("CONDA_PREFIX") {
        bases.push(PathBuf::from(prefix));
    }
    if let Ok(home) = std::env::var("USERPROFILE").or_else(|_| std::env::var("HOME")) {
        bases.push(Path::new(&home).join("miniforge3/envs/mars-sim"));
    }

    bases
        .into_iter()
        .map(|b| b.join("Library/lib"))
        .find(|d| d.is_dir())
}
